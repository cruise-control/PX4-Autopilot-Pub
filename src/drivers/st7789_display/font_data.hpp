/** Map an ASCII character to a LargeGlyph index, or LG_SPACE if unknown. */
static inline int large_glyph_index(char c)
{
    switch (c) {
    case ' ': return LG_SPACE;
    case '-': return LG_MINUS;
    case '+': return LG_PLUS;
    case '.': return LG_DOT;
    default:
        if (c >= '0' && c <= '9') return LG_0 + (c - '0');
        return LG_SPACE;
    }
}
